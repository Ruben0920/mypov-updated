class Command(BaseCommand):
    help = 'Idempotently seeds 15 Cyprus anchor venues across Limassol and Paphos with QRs, vibes, and flash perks.'

    def handle(self, *args, **options):
        now = timezone.now()
        created_count = 0
        updated_count = 0

        for entry in SEED_VENUES:
            venue, created = Venue.objects.update_or_create(
                slug=entry['slug'],
                defaults={
                    'name': entry['name'],
                    'city': entry['city'],
                    'district_corridor': entry['district_corridor'],
                    'latitude': entry['latitude'],
                    'longitude': entry['longitude'],
                    'address': entry['address'],
                    'supported_buckets': entry['supported_buckets'],
                    'interest_tags': entry['interest_tags'],
                    'tier': entry['tier'],
                    'is_weekly_map_anchor': entry['is_weekly_map_anchor'],
                    'default_discount_text': entry['default_discount_text'],
                    'avg_spend_estimate_eur': entry['avg_spend_estimate_eur'],
                    'is_active': True,
                },
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

            for table_idx, label in enumerate(['Table 1', 'Table 2', 'Bar Counter'], start=1):
                token = f"qr_{entry['slug']}_t{table_idx}"
                VenueTableQR.objects.update_or_create(
                    qr_secret_token=token,
                    defaults={
                        'venue': venue,
                        'table_label': label,
                        'is_active': True,
                    },
                )

            if not venue.vibe_reports.filter(expires_at__gt=now).exists():
                crowd, noise, best_for, badge = entry['vibe']
                VenueVibeReport.objects.create(
                    venue=venue,
                    user=None,
                    crowd_level=crowd,
                    noise_level=noise,
                    current_best_for=best_for,
                    vibe_preset_badge=badge,
                    expires_at=now + timedelta(hours=2),
                )

            perk_title, perk_bucket, req_group = entry['perk']
            VenueFlashPerk.objects.get_or_create(
                venue=venue,
                title=perk_title,
                defaults={
                    'target_bucket': perk_bucket,
                    'valid_from': now - timedelta(hours=1),
                    'valid_until': now + timedelta(days=7),
                    'max_redemptions': 25,
                    'requires_companion_or_table': req_group,
                },
            )

        self.stdout.write(
            self.style.SUCCESS(
                f"Seeded Cyprus venues: {created_count} created, {updated_count} updated (total {len(SEED_VENUES)})."
            )
        )
